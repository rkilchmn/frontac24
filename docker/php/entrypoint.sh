#!/usr/bin/env bash
#
# FrontAccounting container entrypoint.
#
# Responsibilities:
#   1. wait for the MariaDB service to accept connections
#   2. render core/config_db.php from environment variables (secrets stay
#      out of git - core/config_db.php is in .gitignore)
#   3. make sure the directories FA writes to exist and are writable
#   4. hand over to php-fpm
#
set -euo pipefail

APP_DIR="${FA_APP_DIR:-/var/www/html}"
PHP_INI_DIR="${PHP_INI_SCAN_DIR:-/usr/local/etc/php/conf.d}"
DB_HOST="${FA_DB_HOST:-db}"
DB_PORT="${FA_DB_PORT:-3306}"
DB_USER="${FA_DB_USER:-frontacc}"
DB_PASS="${FA_DB_PASSWORD:-}"
DB_NAME="${FA_DB_NAME:-frontacc}"
DEF_COY="${FA_DEF_COY:-0}"
TB_COUNTER="${FA_TB_PREF_COUNTER:-7}"
COMPANIES="${FA_COMPANIES:-0|Demo Company|0_}"
POOL_USER="${FA_POOL_USER:-}"
POOL_GROUP="${FA_POOL_GROUP:-}"

log() { printf '[fa-entrypoint] %s\n' "$*"; }

# ---------------------------------------------------------------------------
# 1. database readiness
# ---------------------------------------------------------------------------
wait_for_db() {
	if [ "${FA_WAIT_FOR_DB:-1}" != "1" ]; then
		return 0
	fi
	log "waiting for database ${DB_HOST}:${DB_PORT} ..."
	local i
	for i in $(seq 1 60); do
		if mysqladmin ping -h "$DB_HOST" -P "$DB_PORT" \
			-u"$DB_USER" -p"$DB_PASS" --silent >/dev/null 2>&1; then
			log "database is up"
			return 0
		fi
		sleep 1
	done
	log "WARNING: database not reachable after 60s, starting anyway"
}

# ---------------------------------------------------------------------------
# 2. core/config_db.php from the environment
# ---------------------------------------------------------------------------

# escape a value so it can be used inside a single quoted PHP string
php_escape() {
	printf '%s' "$1" | sed "s/'/\\\\'/g"
}

render_config_db() {
	local target="${FA_CONFIG_DB_TARGET:-$APP_DIR/config_db.php}"
	local tmp
	tmp="$(mktemp)"

	if [ -d "$target" ]; then
		echo "[fa-entrypoint] ERROR: $target is a directory." >&2
		echo "[fa-entrypoint] The host file docker/generated/config_db.php is missing," >&2
		echo "[fa-entrypoint] run 'make dev-env' to create it." >&2
		exit 1
	fi

	{
		printf '<?php\n'
		printf '/* AUTO-GENERATED by the docker entrypoint - do not edit by hand. */\n'
		printf '/* Source: docker/php/entrypoint.sh + FA_DB_* environment variables */\n\n'
		printf '$def_coy = %s;\n' "$DEF_COY"
		printf '$tb_pref_counter = %s;\n' "$TB_COUNTER"
		printf '$db_connections = array (\n'
	} > "$tmp"

	local idx
	local spec name prefix
	local -a specs
	local count=0
	# records are separated by ";", the fields of a record by "|":
	#   <index>|<display name>|<table prefix>
	#
	# strip surrounding quotes: depending on how the value reached us
	# (docker compose, `make`, a shell export) it may still carry them
	COMPANIES="${COMPANIES%\"}"
	COMPANIES="${COMPANIES#\"}"
	COMPANIES="${COMPANIES%\'}"
	COMPANIES="${COMPANIES#\'}"

	IFS=';' read -r -a specs <<< "$COMPANIES"
	for spec in "${specs[@]}"; do
		[ -z "$spec" ] && continue
		IFS='|' read -r idx name prefix <<< "$spec"
		# strip quotes that may surround a single field
		idx="${idx%\"}"; idx="${idx#\"}"
		name="${name%\"}"; name="${name#\"}"
		prefix="${prefix%\"}"; prefix="${prefix#\"}"
		[ -z "$idx" ] && continue
		if ! printf '%s' "$idx" | grep -qE '^[0-9]+$'; then
			echo "[fa-entrypoint] ERROR: invalid company index '$idx' in FA_COMPANIES" >&2
			echo "[fa-entrypoint] expected: <index>|<name>|<table prefix> separated by ';'" >&2
			exit 1
		fi

		{
			printf '  %s =>\n' "$idx"
			printf '  array (\n'
			printf "    'name' => '%s',\n" "$(php_escape "$name")"
			printf "    'host' => '%s',\n" "$(php_escape "$DB_HOST")"
			printf "    'port' => '%s',\n" "$(php_escape "$DB_PORT")"
			printf "    'dbuser' => '%s',\n" "$(php_escape "$DB_USER")"
			printf "    'dbpassword' => '%s',\n" "$(php_escape "$DB_PASS")"
			printf "    'dbname' => '%s',\n" "$(php_escape "$DB_NAME")"
			printf "    'tbpref' => '%s',\n" "$(php_escape "$prefix")"
			printf "    'collation' => 'utf8_xx',\n"
			printf '  ),\n'
		} >> "$tmp"
		count=$((count + 1))
	done

	printf ');\n' >> "$tmp"

	# never serve a broken configuration
	if ! php -l "$tmp" > /dev/null 2>&1; then
		echo "[fa-entrypoint] ERROR: the generated config_db.php is not valid PHP:" >&2
		php -l "$tmp" >&2 || true
		echo "[fa-entrypoint] check FA_COMPANIES and the FA_DB_* variables" >&2
		exit 1
	fi

	# write in place: the target can be a bind mounted file, which cannot be
	# replaced by a rename
	cat "$tmp" > "$target"
	chmod 0644 "$target" 2>/dev/null || true
	rm -f "$tmp"
	log "rendered $target (${count} company/ies, default #$DEF_COY)"
}

# ---------------------------------------------------------------------------
# 3. writable directories
# ---------------------------------------------------------------------------
prepare_dirs() {
	local d
	mkdir -p "$APP_DIR/tmp"
	mkdir -p "$APP_DIR/company"

	# per company working directories used by FA
	for d in "$APP_DIR"/company/*/; do
		[ -d "$d" ] || continue
		mkdir -p "$d/attachments" "$d/backup" "$d/images" \
			"$d/js_cache" "$d/pdf_files" "$d/reporting"
	done

	# modules and language caches are written to at runtime
	mkdir -p "$APP_DIR/lang" "$APP_DIR/modules"
	for d in "$APP_DIR"/modules/*/; do
		[ -d "$d" ] || continue
		mkdir -p "$d"
	done

	if [ "$(id -u)" = "0" ]; then
		local owner="www-data:www-data"
		if [ -n "$POOL_USER" ]; then
			owner="$POOL_USER:$POOL_GROUP"
		fi
		chown -R "$owner" \
			"$APP_DIR/tmp" "$APP_DIR/company" \
			"$APP_DIR/lang" "$APP_DIR/modules" 2>/dev/null || true
		chown "$owner" "$APP_DIR/config_db.php" 2>/dev/null || true
		chmod 1777 "$APP_DIR/tmp" 2>/dev/null || true
		log "ownership set to $owner"
	else
		# dev profile: the container runs as the host user, make sure the
		# directories are writable for that user
		chmod 0777 "$APP_DIR/tmp" 2>/dev/null || true
		log "running as uid $(id -u) - skipping ownership changes"
	fi
}

# ---------------------------------------------------------------------------
# 3b. run the FPM pool as the host user (dev)
# ---------------------------------------------------------------------------
render_pool_user() {
	[ -n "$POOL_USER" ] || return 0
	local f="/usr/local/etc/php-fpm.d/zz-fa-user.conf"
	{
		printf '[www]\n'
		printf 'user = %s\n' "$POOL_USER"
		printf 'group = %s\n' "$POOL_GROUP"
	} > "$f"
	log "FPM pool will run as $POOL_USER:$POOL_GROUP"
}

# ---------------------------------------------------------------------------
# 4. runtime ini from the environment
# ---------------------------------------------------------------------------
render_env_ini() {
	local f="$PHP_INI_DIR/zzz-fa-env.ini"
	{
		printf '[PHP]\n'
		printf 'date.timezone = %s\n' "${FA_TIMEZONE:-UTC}"
		printf 'memory_limit = %s\n' "${FA_MEMORY_LIMIT:-256M}"
		printf 'max_execution_time = %s\n' "${FA_MAX_EXECUTION_TIME:-300}"
	} > "$f"
	log "wrote $f"
}

# ---------------------------------------------------------------------------
# 4b. Xdebug (development only)
# ---------------------------------------------------------------------------
# The extension itself is built into the image with INSTALL_XDEBUG=1 (see
# docker-compose.dev.yml); here it is only switched on and pointed at the
# debugger on the host.
#
# Xdebug 3 works in "connect" mode: the PHP process dials the IDE. The IDE
# is VS Code with the "PHP Debug" extension, listening on port 9003 of the
# host - inside the container that host is "host.docker.internal", which the
# compose file maps to the docker gateway (extra_hosts: host-gateway).
render_xdebug_ini() {
	[ "${FA_XDEBUG:-0}" = "1" ] || return 0

	if ! php -m | grep -qix 'xdebug'; then
		log "WARNING: FA_XDEBUG=1 but the xdebug extension is not in the image."
		log "         rebuild it with INSTALL_XDEBUG=1 (make up-dev)."
		return 0
	fi

	local f="$PHP_INI_DIR/zzz-fa-xdebug.ini"
	local mode="${FA_XDEBUG_MODE:-develop,debug}"
	local host="${FA_XDEBUG_CLIENT_HOST:-host.docker.internal}"
	local port="${FA_XDEBUG_CLIENT_PORT:-9003}"
	local start="${FA_XDEBUG_START_WITH_REQUEST:-yes}"

	{
		printf '[xdebug]\n'
		printf 'xdebug.mode = %s\n' "$mode"
		printf 'xdebug.start_with_request = %s\n' "$start"
		printf 'xdebug.client_host = %s\n' "$host"
		printf 'xdebug.client_port = %s\n' "$port"
		# the IDE is addressed directly, no client discovery header
		printf 'xdebug.client_discovery_header = 0\n'
		printf 'xdebug.discover_client_host = 0\n'
		printf 'xdebug.connect_timeout_ms = 200\n'
		printf 'xdebug.log = /dev/stderr\n'
		printf 'xdebug.log_level = 0\n'
		printf 'xdebug.show_local_vars = 1\n'
		printf 'xdebug.max_nesting_level = 256\n'
	} > "$f"

	log "xdebug enabled: mode=$mode, debugger=$host:$port, start_with_request=$start"
}

wait_for_db
render_config_db
prepare_dirs
render_pool_user
render_env_ini
render_xdebug_ini

log "starting: $*"
exec "$@"
