#!/usr/bin/env bash
#
# Create a test user as a copy of the existing "admin" user of a company.
#
#   scripts/create-test-user.sh [username] [password] [company index]
#
# The new user gets the same role and the same settings as the admin user
# (full access), only the name and the password are different. Handy for
# testing and for handing a separate account to an LLM agent.
#
# With an empty password a random one is generated and printed.
#
set -euo pipefail

cd "$(dirname "$0")/.."

USER_NAME="${1:-llm_agent}"
PASSWORD="${2:-}"
COY="${3:-2}"

# shellcheck disable=SC1091
set -a; . ./.env; set +a
DB_NAME="${DB_NAME:-frontacc}"
DB_USER="${DB_USER:-frontacc}"
DB_PASSWORD="${DB_PASSWORD:-}"
PREFIX="$(printf '%s' "${FA_COMPANIES}" | tr ';' '\n' | awk -F'|' -v c="$COY" '$1==c {print $3}')"

if [ -z "$PREFIX" ]; then
	echo "could not find a table prefix for company index $COY in FA_COMPANIES" >&2
	exit 1
fi

if [ -z "$PASSWORD" ]; then
	PASSWORD="$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 20)"
fi

echo "==> company $COY (prefix $PREFIX), copying the admin user as '$USER_NAME'"

# clone the admin row, then overwrite id, user_id and password
docker compose exec -T db mariadb -u"$DB_USER" -p"$DB_PASSWORD" "$DB_NAME" <<SQL
DELETE FROM ${PREFIX}users WHERE user_id = '${USER_NAME}';
CREATE TEMPORARY TABLE fa_clone LIKE ${PREFIX}users;
INSERT INTO fa_clone SELECT * FROM ${PREFIX}users WHERE user_id = 'admin' LIMIT 1;
UPDATE fa_clone SET id = NULL, user_id = '${USER_NAME}', password = MD5('${PASSWORD}'), last_visit_date = NULL;
INSERT INTO ${PREFIX}users SELECT * FROM fa_clone;
DROP TEMPORARY TABLE fa_clone;
SQL

docker compose exec -T db mariadb -u"$DB_USER" -p"$DB_PASSWORD" "$DB_NAME" \
	-e "SELECT id, user_id, real_name, role_id, inactive FROM ${PREFIX}users;" 2>/dev/null

# store the credentials in Agents.md (gitignored) so the agent can read them
HTTP_PORT_VALUE="$(grep '^HTTP_PORT=' .env | cut -d= -f2 | tr -d '"')"
CRED_FILE="${FA_CREDENTIALS_FILE:-$PWD/Agents.md}"
mkdir -p "$(dirname "$CRED_FILE")"
cat > "$CRED_FILE" <<EOF
# FrontAccounting test credentials

# Generated by scripts/create-test-user.sh - do not commit this file.
# It is listed in .gitignore, keep it out of any git repository or sync folder.

| | |
|---|---|
| URL | http://localhost:${HTTP_PORT_VALUE} |
| User | ${USER_NAME} |
| Password | ${PASSWORD} |
| Company | ${COY} (FTSS) - selected on the login screen |

The account is a clone of the \`admin\` user: full access, all applications.

## Login

1. Open the URL above, pick the company on the login screen, enter user and
   password, press *Log in*.
2. The session cookie is \`FA<hash>\`, path \`/\`, HttpOnly. The frontend
   serves plain http - the session cookie is not flagged "secure" in this
   test setup.

## Reading data without the UI

\`\`\`bash
docker compose exec db mariadb -ufrontacc -p\$(grep '^DB_PASSWORD=' .env | cut -d= -f2) frontacc
\`\`\`

## Rotate the password

\`scripts/agent-credentials.sh rotate\` - rewrites this file and the database.
EOF
chmod 600 "$CRED_FILE"

echo
echo "==> user created"
echo "    user id : $USER_NAME"
echo "    password: $PASSWORD"
echo "    role    : same as the admin user of company $COY (full access)"
echo "    url     : http://localhost:${HTTP_PORT_VALUE}"
echo
echo "    credentials written to $CRED_FILE (mode 600, gitignored)"
echo "    read them back with: scripts/agent-credentials.sh show"
